use tracing::error;

use crate::{
    common::{
        bus::Bus,
        types::{Byte, Cycles},
    },
    cpu::{Cpu, alu, cb, control_flow, load, misc},
};

pub fn execute<B: Bus>(cpu: &mut Cpu, bus: &mut B, opcode: Byte) -> Cycles {
    match opcode {
        0x00 => misc::nop(cpu),
        0x01 => load::ld_bc_n16(cpu, bus),
        0x02 => load::ld_bc_a(cpu, bus),
        0x03 => alu::inc_bc(cpu),
        0x04 => alu::inc_b(cpu),
        0x05 => alu::dec_b(cpu),
        0x06 => load::ld_b_n8(cpu, bus),
        0x07 => misc::rlca(cpu),
        0x08 => load::ld_n16_sp(cpu, bus),
        0x09 => alu::add_hl_bc(cpu),
        0x0A => load::ld_a_bc(cpu, bus),
        0x0B => alu::dec_bc(cpu),
        0x0C => alu::inc_c(cpu),
        0x0D => alu::dec_c(cpu),
        0x0E => load::ld_c_n8(cpu, bus),
        0x0F => misc::rrca(cpu),
        0x10 => misc::stop(cpu, bus),
        0x11 => load::ld_de_n16(cpu, bus),
        0x12 => load::ld_de_a(cpu, bus),
        0x13 => alu::inc_de(cpu),
        0x14 => alu::inc_d(cpu),
        0x15 => alu::dec_d(cpu),
        0x16 => load::ld_d_n8(cpu, bus),
        0x17 => misc::rla(cpu),
        0x18 => control_flow::jr_e8(cpu, bus),
        0x19 => alu::add_hl_de(cpu),
        0x1A => load::ld_a_de(cpu, bus),
        0x1B => alu::dec_de(cpu),
        0x1C => alu::inc_e(cpu),
        0x1D => alu::dec_e(cpu),
        0x1E => load::ld_e_n8(cpu, bus),
        0x1F => misc::rra(cpu),
        0x20 => control_flow::jr_nz_e8(cpu, bus),
        0x21 => load::ld_hl_n16(cpu, bus),
        0x22 => load::ld_hli_a(cpu, bus),
        0x23 => alu::inc_hl16(cpu),
        0x24 => alu::inc_h(cpu),
        0x25 => alu::dec_h(cpu),
        0x26 => load::ld_h_n8(cpu, bus),
        0x27 => alu::daa(cpu),
        0x28 => control_flow::jr_z_e8(cpu, bus),
        0x29 => alu::add_hl_hl(cpu),
        0x2A => load::ld_a_hli(cpu, bus),
        0x2B => alu::dec_hl16(cpu),
        0x2C => alu::inc_l(cpu),
        0x2D => alu::dec_l(cpu),
        0x2E => load::ld_l_n8(cpu, bus),
        0x2F => alu::cpl(cpu),
        0x30 => control_flow::jr_nc_e8(cpu, bus),
        0x31 => load::ld_sp_n16(cpu, bus),
        0x32 => load::ld_hld_a(cpu, bus),
        0x33 => alu::inc_sp(cpu),
        0x34 => alu::inc_hl(cpu, bus),
        0x35 => alu::dec_hl(cpu, bus),
        0x36 => load::ld_hl_n8(cpu, bus),
        0x37 => alu::scf(cpu),
        0x38 => control_flow::jr_c_e8(cpu, bus),
        0x39 => alu::add_hl_sp(cpu),
        0x3A => load::ld_a_hld(cpu, bus),
        0x3B => alu::dec_sp(cpu),
        0x3C => alu::inc_a(cpu),
        0x3D => alu::dec_a(cpu),
        0x3E => load::ld_a_n8(cpu, bus),
        0x3F => alu::ccf(cpu),
        0x40 => load::ld_b_b(cpu),
        0x41 => load::ld_b_c(cpu),
        0x42 => load::ld_b_d(cpu),
        0x43 => load::ld_b_e(cpu),
        0x44 => load::ld_b_h(cpu),
        0x45 => load::ld_b_l(cpu),
        0x46 => load::ld_b_hl(cpu, bus),
        0x47 => load::ld_b_a(cpu),
        0x48 => load::ld_c_b(cpu),
        0x49 => load::ld_c_c(cpu),
        0x4A => load::ld_c_d(cpu),
        0x4B => load::ld_c_e(cpu),
        0x4C => load::ld_c_h(cpu),
        0x4D => load::ld_c_l(cpu),
        0x4E => load::ld_c_hl(cpu, bus),
        0x4F => load::ld_c_a(cpu),
        0x50 => load::ld_d_b(cpu),
        0x51 => load::ld_d_c(cpu),
        0x52 => load::ld_d_d(cpu),
        0x53 => load::ld_d_e(cpu),
        0x54 => load::ld_d_h(cpu),
        0x55 => load::ld_d_l(cpu),
        0x56 => load::ld_d_hl(cpu, bus),
        0x57 => load::ld_d_a(cpu),
        0x58 => load::ld_e_b(cpu),
        0x59 => load::ld_e_c(cpu),
        0x5A => load::ld_e_d(cpu),
        0x5B => load::ld_e_e(cpu),
        0x5C => load::ld_e_h(cpu),
        0x5D => load::ld_e_l(cpu),
        0x5E => load::ld_e_hl(cpu, bus),
        0x5F => load::ld_e_a(cpu),
        0x60 => load::ld_h_b(cpu),
        0x61 => load::ld_h_c(cpu),
        0x62 => load::ld_h_d(cpu),
        0x63 => load::ld_h_e(cpu),
        0x64 => load::ld_h_h(cpu),
        0x65 => load::ld_h_l(cpu),
        0x66 => load::ld_h_hl(cpu, bus),
        0x67 => load::ld_h_a(cpu),
        0x68 => load::ld_l_b(cpu),
        0x69 => load::ld_l_c(cpu),
        0x6A => load::ld_l_d(cpu),
        0x6B => load::ld_l_e(cpu),
        0x6C => load::ld_l_h(cpu),
        0x6D => load::ld_l_l(cpu),
        0x6E => load::ld_l_hl(cpu, bus),
        0x6F => load::ld_l_a(cpu),
        0x70 => load::ld_hl_b(cpu, bus),
        0x71 => load::ld_hl_c(cpu, bus),
        0x72 => load::ld_hl_d(cpu, bus),
        0x73 => load::ld_hl_e(cpu, bus),
        0x74 => load::ld_hl_h(cpu, bus),
        0x75 => load::ld_hl_l(cpu, bus),
        0x76 => misc::halt(cpu),
        0x77 => load::ld_hl_a(cpu, bus),
        0x78 => load::ld_a_b(cpu),
        0x79 => load::ld_a_c(cpu),
        0x7A => load::ld_a_d(cpu),
        0x7B => load::ld_a_e(cpu),
        0x7C => load::ld_a_h(cpu),
        0x7D => load::ld_a_l(cpu),
        0x7E => load::ld_a_hl(cpu, bus),
        0x7F => load::ld_a_a(cpu),
        0x80 => alu::add_a_b(cpu),
        0x81 => alu::add_a_c(cpu),
        0x82 => alu::add_a_d(cpu),
        0x83 => alu::add_a_e(cpu),
        0x84 => alu::add_a_h(cpu),
        0x85 => alu::add_a_l(cpu),
        0x86 => alu::add_a_hl(cpu, bus),
        0x87 => alu::add_a_a(cpu),
        0x88 => alu::adc_a_b(cpu),
        0x89 => alu::adc_a_c(cpu),
        0x8A => alu::adc_a_d(cpu),
        0x8B => alu::adc_a_e(cpu),
        0x8C => alu::adc_a_h(cpu),
        0x8D => alu::adc_a_l(cpu),
        0x8E => alu::adc_a_hl(cpu, bus),
        0x8F => alu::adc_a_a(cpu),
        0x90 => alu::sub_a_b(cpu),
        0x91 => alu::sub_a_c(cpu),
        0x92 => alu::sub_a_d(cpu),
        0x93 => alu::sub_a_e(cpu),
        0x94 => alu::sub_a_h(cpu),
        0x95 => alu::sub_a_l(cpu),
        0x96 => alu::sub_a_hl(cpu, bus),
        0x97 => alu::sub_a_a(cpu),
        0x98 => alu::sbc_a_b(cpu),
        0x99 => alu::sbc_a_c(cpu),
        0x9A => alu::sbc_a_d(cpu),
        0x9B => alu::sbc_a_e(cpu),
        0x9C => alu::sbc_a_h(cpu),
        0x9D => alu::sbc_a_l(cpu),
        0x9E => alu::sbc_a_hl(cpu, bus),
        0x9F => alu::sbc_a_a(cpu),
        0xA0 => alu::and_a_b(cpu),
        0xA1 => alu::and_a_c(cpu),
        0xA2 => alu::and_a_d(cpu),
        0xA3 => alu::and_a_e(cpu),
        0xA4 => alu::and_a_h(cpu),
        0xA5 => alu::and_a_l(cpu),
        0xA6 => alu::and_a_hl(cpu, bus),
        0xA7 => alu::and_a_a(cpu),
        0xA8 => alu::xor_a_b(cpu),
        0xA9 => alu::xor_a_c(cpu),
        0xAA => alu::xor_a_d(cpu),
        0xAB => alu::xor_a_e(cpu),
        0xAC => alu::xor_a_h(cpu),
        0xAD => alu::xor_a_l(cpu),
        0xAE => alu::xor_a_hl(cpu, bus),
        0xAF => alu::xor_a_a(cpu),
        0xB0 => alu::or_a_b(cpu),
        0xB1 => alu::or_a_c(cpu),
        0xB2 => alu::or_a_d(cpu),
        0xB3 => alu::or_a_e(cpu),
        0xB4 => alu::or_a_h(cpu),
        0xB5 => alu::or_a_l(cpu),
        0xB6 => alu::or_a_hl(cpu, bus),
        0xB7 => alu::or_a_a(cpu),
        0xB8 => alu::cp_a_b(cpu),
        0xB9 => alu::cp_a_c(cpu),
        0xBA => alu::cp_a_d(cpu),
        0xBB => alu::cp_a_e(cpu),
        0xBC => alu::cp_a_h(cpu),
        0xBD => alu::cp_a_l(cpu),
        0xBE => alu::cp_a_hl(cpu, bus),
        0xBF => alu::cp_a_a(cpu),
        0xC0 => control_flow::ret_nz(cpu, bus),
        0xC1 => load::pop_bc(cpu, bus),
        0xC2 => control_flow::jp_nz_nn(cpu, bus),
        0xC3 => control_flow::jp_nn(cpu, bus),
        0xC4 => control_flow::call_nz_nn(cpu, bus),
        0xC5 => load::push_bc(cpu, bus),
        0xC6 => alu::add_a_n8(cpu, bus),
        0xC7 => control_flow::rst_00(cpu, bus),
        0xC8 => control_flow::ret_z(cpu, bus),
        0xC9 => control_flow::ret(cpu, bus),
        0xCA => control_flow::jp_z_nn(cpu, bus),
        0xCB => {
            let cb_opcode: Byte = cpu.fetch_byte(bus);
            cb::execute(cpu, bus, cb_opcode)
        }
        0xCC => control_flow::call_z_nn(cpu, bus),
        0xCD => control_flow::call_nn(cpu, bus),
        0xCE => alu::adc_a_n8(cpu, bus),
        0xCF => control_flow::rst_08(cpu, bus),
        0xD0 => control_flow::ret_nc(cpu, bus),
        0xD1 => load::pop_de(cpu, bus),
        0xD2 => control_flow::jp_nc_nn(cpu, bus),
        0xD4 => control_flow::call_nc_nn(cpu, bus),
        0xD5 => load::push_de(cpu, bus),
        0xD6 => alu::sub_a_n8(cpu, bus),
        0xD7 => control_flow::rst_10(cpu, bus),
        0xD8 => control_flow::ret_c(cpu, bus),
        0xD9 => control_flow::reti(cpu, bus),
        0xDA => control_flow::jp_c_nn(cpu, bus),
        0xDC => control_flow::call_c_nn(cpu, bus),
        0xDE => alu::sbc_a_n8(cpu, bus),
        0xDF => control_flow::rst_18(cpu, bus),
        0xE0 => load::ldh_n8_a(cpu, bus),
        0xE1 => load::pop_hl(cpu, bus),
        0xE2 => load::ldh_c_a(cpu, bus),
        0xE5 => load::push_hl(cpu, bus),
        0xE6 => alu::and_a_n8(cpu, bus),
        0xE7 => control_flow::rst_20(cpu, bus),
        0xE8 => alu::add_sp_e8(cpu, bus),
        0xE9 => control_flow::jp_hl(cpu),
        0xEA => load::ld_n16_a(cpu, bus),
        0xEE => alu::xor_a_n8(cpu, bus),
        0xEF => control_flow::rst_28(cpu, bus),
        0xF0 => load::ldh_a_n8(cpu, bus),
        0xF1 => load::pop_af(cpu, bus),
        0xF2 => load::ldh_a_c(cpu, bus),
        0xF3 => misc::di(cpu),
        0xF5 => load::push_af(cpu, bus),
        0xF6 => alu::or_a_n8(cpu, bus),
        0xF7 => control_flow::rst_30(cpu, bus),
        0xF8 => load::ld_hl_sp_e8(cpu, bus),
        0xF9 => load::ld_sp_hl(cpu),
        0xFA => load::ld_a_n16(cpu, bus),
        0xFB => misc::ei(cpu),
        0xFE => alu::cp_a_n8(cpu, bus),
        0xFF => control_flow::rst_38(cpu, bus),
        _ => {
            error!("Opcode {:#04X} not yet implemented", opcode);
            0
        }
    }
}

